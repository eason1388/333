export function getReadingTerms(text){
  const normalized=String(text||'').normalize('NFKC').replace(/[\u3400-\u9fff]/g,char=>variants[char]||char);
  const found=terms.filter(([,pattern])=>pattern.test(normalized)).map(([term,,meaning])=>({term,meaning}));
  if(/得位|得地|得垣|貴鄉|旺地|旺宮|廟|失陷|落陷/.test(normalized)){
    for(const [star,positions] of Object.entries(dignity)){
      if(normalized.includes(star))found.push({term:`${star}得位地支（卷三表）`,meaning:positions});
    }
  }
  return found;
}

export function appendReadingTerms(parent,text){
  const found=getReadingTerms(text);
  if(!found.length)return;
  const section=document.createElement('section');
  section.className='reading-terms';
  section.setAttribute('aria-label','本段星曜與宮位說明');
  const heading=document.createElement('h4');
  heading.textContent='本段星曜與宮位';
  const list=document.createElement('dl');
  for(const {term,meaning} of found){
    const title=document.createElement('dt');title.textContent=term;
    const definition=document.createElement('dd');definition.textContent=meaning;
    list.append(title,definition);
  }
  section.append(heading,list);parent.append(section);
}
